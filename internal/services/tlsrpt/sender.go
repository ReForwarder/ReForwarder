package tlsrpt

import (
	"bytes"
	"compress/gzip"
	"context"
	"fmt"
	"time"
)

// OutboundReportRequest is one generated report the sender must deliver.
type OutboundReportRequest struct {
	// ReportID is the RFC 8460 report-id (deterministic per window + policy
	// domain, so a retry cannot double-send under a new identity).
	ReportID string
	// PolicyDomain is the domain the report is about.
	PolicyDomain string
	// Window is the covered interval.
	WindowStart, WindowEnd time.Time
	// JSON is the report document (RFC 8460 §7.2).
	JSON []byte
	// To holds the rua mailto endpoints discovered from the policy domain's
	// live _smtp._tls TXT record.
	To []string
	// From is the generator address (e.g. mta-sts-report@<ehlo-domain>).
	From string
}

// Sender delivers one generated outbound report. The production adapter
// (built in cmd wiring) enqueues the report through the standard outbound
// pipeline with system provenance; tests inject fakes.
type Sender interface {
	SendReport(ctx context.Context, req *OutboundReportRequest) error
}

// SenderFunc adapts a function onto Sender.
type SenderFunc func(ctx context.Context, req *OutboundReportRequest) error

// SendReport implements Sender.
func (f SenderFunc) SendReport(ctx context.Context, req *OutboundReportRequest) error {
	if f == nil {
		return fmt.Errorf("tlsrpt: no report sender wired")
	}
	return f(ctx, req)
}

// GzipAttachment gzips the report document for transport (RFC 8460 §7.3:
// reports SHOULD be gzip-compressed, application/tlsrpt+json). The result
// carries the attachment filename "<report-id>.json.gz".
func GzipAttachment(req *OutboundReportRequest) (filename string, body []byte, err error) {
	if req == nil || len(req.JSON) == 0 {
		return "", nil, fmt.Errorf("tlsrpt: no report document to attach")
	}
	var buf bytes.Buffer
	zw := gzip.NewWriter(&buf)
	if _, err := zw.Write(req.JSON); err != nil {
		return "", nil, err
	}
	if err := zw.Close(); err != nil {
		return "", nil, err
	}
	return req.ReportID + ".json.gz", buf.Bytes(), nil
}

// ReportText is the plain-text body carried with the report attachment.
func ReportText(req *OutboundReportRequest) string {
	if req == nil {
		return ""
	}
	return fmt.Sprintf(
		"This is an aggregate SMTP TLS report for domain %s, generated by the ReForwarder outbound MTA.\n"+
			"Report-ID: %s\nWindow: %s .. %s\nThe report document is attached (application/tlsrpt+json, gzip).\n",
		req.PolicyDomain, req.ReportID,
		req.WindowStart.UTC().Format(time.RFC3339), req.WindowEnd.UTC().Format(time.RFC3339),
	)
}
